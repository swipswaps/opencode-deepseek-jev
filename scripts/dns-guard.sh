#!/usr/bin/env bash
# dns-guard.sh — automated DNS recovery loop telemetry (detection always,
# remediation only with --fix). Uses the ledger DB as the durable record so
# the next occurrence is a lookup, not a fresh investigation.
#
# Usage (any host):
#   bash scripts/dns-guard.sh         # detect + record, never mutates
#   bash scripts/dns-guard.sh --fix   # detect + record + remediate tailnet-DNS
# Verdicts: HEALTHY, BROKEN-tailnet-dns, BROKEN-stale, NOT-APPLICABLE.
# Exit 0 healthy/not-applicable, 2 broken.
# --fix runs `tailscale up --accept-dns=false` (no daemon restart: an SSH
# session riding the tailnet survives it; a tailscaled restart would not).
# Plain ASCII. No sed. No rm -rf. No set -e.
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 3
FIX=0
if [ "${1:-}" = "--fix" ]; then FIX=1; fi
record() {
    python3 scripts/ledger.py record --type NET --verdict "$1" --detail "$2" 2>&1 | head -n 1 || true
}
if ! getent ahostsv4 fedoraproject.org 2>&1 | grep -q STREAM; then
    if command -v tailscale 2>&1 | grep -q tailscale; then
        if grep -q "generated by tailscale" /etc/resolv.conf 2>&1; then
            VERDICT="BROKEN-tailnet-dns"
        else
            VERDICT="BROKEN-stale"
        fi
    else
        VERDICT="BROKEN-stale"
    fi
    printf 'verdict: %s (name resolution fails)\n' "$VERDICT"
    record "$VERDICT" "getent fedoraproject.org empty on $(hostname)"
    if [ "$FIX" -eq 1 ] && [ "$VERDICT" = "BROKEN-tailnet-dns" ]; then
        if printf '%s' "${SSH_CONNECTION:-}" | grep -q "^100\."; then
            printf 'WARN: SSH rides the tailnet; --fix keeps the daemon up (no restart), names fall back to hotspot DNS\n'
        fi
        sudo tailscale up --accept-dns=false 2>&1 || exit 2
        if getent ahostsv4 fedoraproject.org 2>&1 | grep -q STREAM; then
            printf 'RECOVERED: resolution works after --accept-dns=false\n'
            record "RECOVERED" "accept-dns=false on $(hostname)"
            exit 0
        fi
        printf 'STILL-BROKEN after --fix; see tailscale admin DNS policy\n'
        exit 2
    fi
    if [ "$FIX" -eq 0 ]; then
        printf 'action: re-run with --fix to remediate, or inspect manually\n'
    fi
    exit 2
fi
printf 'verdict: HEALTHY (resolution works)\n'
record "HEALTHY" "getent fedoraproject.org ok on $(hostname)"
exit 0
