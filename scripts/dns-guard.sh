#!/usr/bin/env bash
# dns-guard.sh — automated DNS recovery loop telemetry (detection always,
# remediation only with --fix). Uses the ledger DB as the durable record so
# the next occurrence is a lookup, not a fresh investigation.
#
# Provenance: Fedora .45 incident 2026-10-12. Tailscale owned resolv.conf
# (single upstream 100.100.100.100) with an EMPTY upstream set
# (tailscaled: "no upstream resolvers set, returning SERVFAIL") because
# systemd-resolved was inactive, so nothing was harvested. --accept-dns
# was inert on that daemon (no such pref persisted). Enabling resolved +
# restarting tailscaled restored resolution (getent + ping google.com).
#
# Usage (any host):
#   bash scripts/dns-guard.sh         # detect + record, never mutates
#   bash scripts/dns-guard.sh --fix   # detect + record + staged remediation
# Verdicts: HEALTHY, BROKEN-tailnet-dns, BROKEN-stale.
# Exit 0 healthy, 2 broken.
#
# --fix stages (redundant: each verified before the next):
#   1. Daemon-safe: `tailscale up --accept-dns=false` (no restart; a
#      tailnet-riding SSH session survives it). Verify via getent.
#   2. Proven .45 sequence: enable systemd-resolved (the harvest source),
#      then restart tailscaled. The restart DROPS tailnet transport, so it
#      runs only when SSH is NOT riding 100.x; otherwise the exact LAN-shell
#      command is printed as a human checkpoint (repo-wizard rule).
#   3. Redundant verification uses TWO independent lookups (getent NSS path
#      + python socket path); both must agree before RECOVERED is recorded.
# Plain ASCII. No sed. No rm -rf. No set -e.
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 3
FIX=0
if [ "${1:-}" = "--fix" ]; then FIX=1; fi
record() {
    # Standalone runs (e.g. /tmp copy on a peer host) have no repo checkout:
    # resolve the ledger by absolute path and skip silently when absent.
    if [ -f "$REPO/scripts/ledger.py" ]; then
        python3 "$REPO/scripts/ledger.py" record --type NET --verdict "$1" --detail "$2" 2>&1 | head -n 1 || true
    fi
}
# Redundant check: NSS path AND python resolver path must both fail to
# declare BROKEN (one flaky path is not an outage).
resolves() {
    if getent ahostsv4 fedoraproject.org 2>&1 | grep -q STREAM; then return 0; fi
    if python3 -c "import socket; socket.getaddrinfo('fedoraproject.org', 80)" 2>&1; then return 0; fi
    return 1
}
if resolves; then
    printf 'verdict: HEALTHY (resolution works)\n'
    record "HEALTHY" "dual-path lookup ok on $(hostname)"
    exit 0
fi
if command -v tailscale 2>&1 | grep -q tailscale; then
    if grep -q "generated by tailscale" /etc/resolv.conf 2>&1; then
        VERDICT="BROKEN-tailnet-dns"
    else
        VERDICT="BROKEN-stale"
    fi
else
    VERDICT="BROKEN-stale"
fi
printf 'verdict: %s (name resolution fails on both paths)\n' "$VERDICT"
record "$VERDICT" "dual-path lookup empty on $(hostname)"
if [ "$FIX" -eq 0 ]; then
    printf 'action: re-run with --fix to remediate, or inspect manually\n'
    exit 2
fi
# Stage 1: daemon-safe pref flip; harmless if inert, verified after.
if [ "$VERDICT" = "BROKEN-tailnet-dns" ]; then
    sudo tailscale up --accept-dns=false 2>&1 || true
    sleep 3
    if resolves; then
        printf 'RECOVERED stage 1: resolution works after --accept-dns=false\n'
        record "RECOVERED" "stage1 accept-dns=false on $(hostname)"
        exit 0
    fi
    printf 'stage 1 inert; proceeding to stage 2 (proven .45 sequence)\n'
fi
# Stage 2: harvest source + daemon restart. Refuse the restart over tailnet
# SSH: killing tailscaled kills this transport (proven hazard, not theory).
if printf '%s' "${SSH_CONNECTION:-}" | grep -q "^100\."; then
    printf 'REFUSED restart over tailnet SSH (would drop this session).\n'
    printf 'human checkpoint, LAN shell (ssh owner@<lan-ip>):\n'
    printf '  sudo systemctl enable --now systemd-resolved\n'
    printf '  sudo systemctl restart tailscaled; sleep 10\n'
    printf '  bash scripts/dns-guard.sh\n'
    exit 2
fi
sudo systemctl enable --now systemd-resolved 2>&1 || exit 2
sleep 3
sudo systemctl restart tailscaled 2>&1 || exit 2
sleep 10
if resolves; then
    printf 'RECOVERED stage 2: resolution works after resolved+tailscaled restart\n'
    record "RECOVERED" "stage2 resolved+restart on $(hostname)"
    exit 0
fi
printf 'STILL-BROKEN after --fix; see tailnet admin DNS policy\n'
exit 2
